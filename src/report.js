import fs from 'node:fs/promises';
import path from 'node:path';
import Handlebars from 'handlebars';

export async function renderReport(config, check) {
  const packages = [...check.results]
    .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))
    .map(x => ({ ...x, exemption: config.report.includeExemptions ? x.exemption : undefined, licenseText: config.report.includeLicenseText ? x.licenseText?.trim() : undefined }));
  if (config.report.format === 'json') return `${JSON.stringify({ projectLicense: config.project.license, policy: check.policy, packages }, null, 2)}\n`;
  if (config.report.template) {
    const source = await fs.readFile(path.resolve(config.root, config.report.template), 'utf8');
    return normalize(Handlebars.compile(source, { noEscape: true, strict: false })({ title: config.report.title ?? 'Third-Party Licenses', packages }));
  }
  const sections = packages.map(item => {
    const lines = [`## ${item.name}@${item.version}`, '', `- License: ${item.licenseExpression ?? 'UNKNOWN'}`];
    if (item.repository) lines.push(`- Repository: ${item.repository}`);
    lines.push(`- Decision: ${item.status}`);
    lines.push(`- Evidence: ${(item.evidenceSources ?? [item.evidence]).filter(Boolean).join(', ')}`);
    if (item.selected) lines.push(`- Selected SPDX alternative: ${item.selected}`);
    if (item.copyright) lines.push(`- Copyright: ${item.copyright}`);
    if (item.exemption) lines.push(`- Exemption: ${item.exemption.reason ?? 'No reason provided'}`);
    if (item.licenseText) appendFencedText(lines, item.licenseText);
    if (item.noticeText) { lines.push('', '### NOTICE'); appendFencedText(lines, item.noticeText.trim()); }
    return lines.join('\n');
  });
  return normalize(`# ${config.report.title ?? 'Third-Party Licenses'}\n\n> Generated by oss-license-guard. This report is not legal advice.\n\n${sections.join('\n\n')}`);
}

export async function writeReport(config, content) {
  const target = path.resolve(config.root, config.report.path);
  await fs.mkdir(path.dirname(target), { recursive: true });
  const temporary = `${target}.${process.pid}.tmp`;
  await fs.writeFile(temporary, content);
  await fs.rename(temporary, target);
  return target;
}

export async function verifyReport(config, content) {
  const target = path.resolve(config.root, config.report.path);
  try { return { current: await fs.readFile(target, 'utf8'), target }; } catch { return { current: null, target }; }
}

function normalize(value) { return `${value.replace(/\r\n/g, '\n').trimEnd()}\n`; }

function appendFencedText(lines, text) {
  const longest = Math.max(3, ...[...text.matchAll(/`+/g)].map(match => match[0].length + 1));
  const fence = '`'.repeat(longest);
  lines.push('', `${fence}text`, text, fence);
}
